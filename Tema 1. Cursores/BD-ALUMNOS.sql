CREATE DATABASE ALUMNOSMATRICULADOS
GO

USE ALUMNOSMATRICULADOS
GO

CREATE TABLE ALUMNOS (
	DNI		VARCHAR(10)	NOT NULL,
	APENOM	VARCHAR(30),
	DIREC	VARCHAR(30),
	POBLA	VARCHAR(15),
	TELEF	VARCHAR(10),
	CONSTRAINT pk_alumnos PRIMARY KEY (DNI)
);
GO

CREATE TABLE ASIGNATURAS (
	COD		INT	NOT NULL,
	NOMBRE	VARCHAR(25),
	CONSTRAINT pk_asignaturas PRIMARY KEY (COD)
);
GO

CREATE TABLE NOTAS (
	DNI		VARCHAR(10)	NOT NULL,
	COD		INT	NOT NULL,
	NOTA	DECIMAL(4,2),
	CONSTRAINT pk_notas PRIMARY KEY (dni, cod),
	CONSTRAINT fk_notas_alumnos_dni FOREIGN KEY (DNI) REFERENCES ALUMNOS(DNI),
    CONSTRAINT fk_notas_asignaturas_cod FOREIGN KEY (COD) REFERENCES ASIGNATURAS(COD)
);
GO

